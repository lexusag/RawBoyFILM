#!/bin/sh
# Generates the Metal develop shaders from <repo>/shaders (the source of truth, shared with Android and the web).
# The fragment shader is assembled exactly as engine/.../gl/Shaders.kt does (header, develop.glsl, main_body.glsl,
# LUT, curves and output lines), compiled to SPIR-V by glslang (Vulkan "relaxed" rules gather the loose uniforms into one
# block) and translated to MSL by SPIRV-Cross. Outputs, in ios/build/generated/:
#   develop_vert.metal, develop_frag.metal (preview, float out), develop_export.metal (16-bit unsigned out)
#   DevelopLayout.swift: uniform offsets and texture/buffer indices from SPIRV-Cross's reflection
# Where shaders/film exists (RawBoy Film's own repository, GPLv3), RawBoyFilmEngine gets the same files in
# ios/build/generated-film/, assembled as Shaders.kt does for Android's film edition: "#define RAWBOY_FILM 1" and
# shaders/film/film.glsl after develop.glsl.
# Needs glslang and spirv-cross (brew install glslang spirv-cross). Run by xcodegen and by a pre-build phase.
set -e
cd "$(dirname "$0")/.."
SRC=../shaders
PATH="$PATH:/opt/homebrew/bin:/usr/local/bin"

generate() {  # generate <out dir> <temp dir> <film: 0 or 1>
OUT=$1
TMP=$2
FILM=$3
mkdir -p "$OUT" "$TMP"

header() {  # header <out declaration>
    # GLSL ES 3.10 for SPIR-V (3.00 has no SPIR-V target); everything else as Shaders.kt.
    printf '#version 310 es\nprecision highp float;\nprecision highp int;\nprecision highp sampler2D;\nprecision highp sampler3D;\n'
    if [ "$FILM" = 1 ]; then printf '#define RAWBOY_FILM 1\n'; fi
    printf '%s\n' "$1"
}

body() {  # develop.glsl, the film formation (film edition: spektrafilm's), main_body.glsl
    cat "$SRC/develop.glsl"
    if [ "$FILM" = 1 ]; then cat "$SRC/film/film.glsl"; else cat "$SRC/film_form.glsl"; fi
    cat "$SRC/main_body.glsl"
}

{ header "out vec4 fragColor;"; body
  printf '    if (uLutAmount > 0.0) c = clamp(applyLut(c), 0.0, 1.0);\n    if (uCurveOn > 0.0) c = applyCurves(c);\n'
  printf '    if (uClipWarn > 0.0) c = clipWarning(c);\n    fragColor = vec4(c, 1.0);\n}\n'
} > "$TMP/develop_frag.frag"

{ header "out uvec4 fragColor;"; body
  printf '    if (uLutAmount > 0.0) c = clamp(applyLut(c), 0.0, 1.0);\n    if (uCurveOn > 0.0) c = applyCurves(c);\n'
  # 16-bit unsigned integer target, as Android's export: exact, no float rounding of the output.
  printf '    fragColor = uvec4(uvec3(c * 65535.0 + 0.5), 65535u);\n}\n'
} > "$TMP/develop_export.frag"

sed 's/#version 300 es/#version 310 es/' "$SRC/develop.vert" > "$TMP/develop_vert.vert"

translate() {  # translate <name> <stage file> <entry point>
    glslangValidator -V -R --aml --amb --quiet -o "$TMP/$1.spv" "$TMP/$2"
    spirv-cross "$TMP/$1.spv" --msl --msl-version 20100 --msl-ios --msl-decoration-binding \
        --rename-entry-point main "$3" "$4" --output "$OUT/$1.metal"
    spirv-cross "$TMP/$1.spv" --reflect --output "$TMP/$1.json"
}
translate develop_vert develop_vert.vert developVertex vert
translate develop_frag develop_frag.frag developFragment frag
translate develop_export develop_export.frag developExportFragment frag

python3 -I - "$TMP" "$OUT/DevelopLayout.swift" << 'EOF'
import json, sys
tmp, out = sys.argv[1], sys.argv[2]

def layout(name):
    r = json.load(open(f"{tmp}/{name}.json"))
    ubo = r["ubos"][0]
    members = r["types"][ubo["type"]]["members"]
    uniforms = {m["name"]: (m["offset"], m.get("array_stride", 0), m.get("matrix_stride", 0), m["type"]) for m in members}
    textures = {t["name"]: t["binding"] for t in r.get("textures", [])}
    # SPIRV-Cross pads the MSL struct to 16 bytes; Metal validation rejects a buffer shorter than the struct.
    return (ubo["block_size"] + 15) // 16 * 16, ubo["binding"], uniforms, textures

vsize, vbuf, vuni, _ = layout("develop_vert")
fsize, fbuf, funi, ftex = layout("develop_frag")
esize, ebuf, euni, etex = layout("develop_export")
if (fsize, funi, ftex) != (esize, euni, etex):
    sys.exit("gen.sh: preview and export fragment shaders have different layouts")

def table(u):
    return "\n".join(f'        "{n}": .init(offset: {o}, arrayStride: {a}, matrixStride: {m}),  // {t}'
                     for n, (o, a, m, t) in sorted(u.items(), key=lambda kv: kv[1][0]))

swift = f"""// Generated by ios/shaders/gen.sh from <repo>/shaders. Do not edit.

/** Where SPIRV-Cross put the develop shader's uniforms (std140 offsets in the one uniform block) and textures. */
enum DevelopLayout {{
    struct Uniform {{
        let offset: Int
        /** Bytes between array elements, 0 for a single value. */
        let arrayStride: Int
        /** Bytes between matrix columns, 0 for a non-matrix. */
        let matrixStride: Int
    }}

    static let vertexBlockSize = {vsize}
    static let vertexBufferIndex = {vbuf}
    static let vertexUniforms: [String: Uniform] = [
{table(vuni)}
    ]

    static let fragmentBlockSize = {fsize}
    static let fragmentBufferIndex = {fbuf}
    static let fragmentUniforms: [String: Uniform] = [
{table(funi)}
    ]

    /** Texture (and sampler) index of each sampler uniform. */
    static let textures: [String: Int] = [
{chr(10).join(f'        "{n}": {b},' for n, b in sorted(ftex.items(), key=lambda kv: kv[1]))}
    ]
}}
"""
open(out, "w").write(swift)
EOF
}

generate build/generated build/shaders 0
if [ -d "$SRC/film" ]; then generate build/generated-film build/shaders-film 1; fi
