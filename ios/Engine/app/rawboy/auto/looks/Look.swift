import Foundation

/**
 * A film look: one of the bundled LUTs plus adjustments added on top of the auto
 * develop. Deltas are in slider units (see DevelopParams); all are scaled by Strength.
 */
public struct Look: Equatable, Hashable, Sendable, Identifiable {
    public let id: String
    public let name: String
    /** Bundled LUT file in luts/, or nil for none. */
    public let lutFile: String?
    public var lutAmount: Float = 100
    public var exposure: Float = 0
    public var contrast: Float = 0
    public var saturation: Float = 0
    public var highlights: Float = 0
    public var blacks: Float = 0
    public var whites: Float = 0
    public var grain: Float = 0
    public var bloom: Float = 0
    public var highpass: Float = 0
    public var vignette: Float = 0
    /** Kelvin added to the white balance; + is warmer. */
    public var warmth: Float = 0
    /** Skin retouch applied when the photo has a face. */
    public var portraitRetouch: Float = 0
    public var monochrome: Bool = false
    /** spektrafilm stock id (FilmStocks) rendered instead of AgX + LUT, or nil. */
    public var film: String? = nil
    /** Film grain and halation, 100 = as spektrafilm simulates the stock. */
    public var filmGrain: Float = 100
    public var halation: Float = 100

    init(_ id: String, _ name: String, _ lutFile: String?, contrast: Float = 0, grain: Float = 0, bloom: Float = 0,
         highpass: Float = 0, vignette: Float = 0, warmth: Float = 0, portraitRetouch: Float = 0,
         monochrome: Bool = false, film: String? = nil) {
        self.id = id
        self.name = name
        self.lutFile = lutFile
        self.contrast = contrast
        self.grain = grain
        self.bloom = bloom
        self.highpass = highpass
        self.vignette = vignette
        self.warmth = warmth
        self.portraitRetouch = portraitRetouch
        self.monochrome = monochrome
        self.film = film
    }

    /** LutEntry id, as LutRepository names bundled LUTs. */
    public var lutId: String? { lutFile.map { "asset:luts/\($0)" } }
}

/**
 * The looks RawBoy Auto offers, built on the LUTs in <repo>/luts.
 *
 * The film LUTs are generated by tools/film_luts/generate.py from datasheet simulations.
 * Each one already replaces AgX's tone curve with the film's and keeps middle grey, so
 * looks only add what a LUT can't: grain by film speed, bloom on the fast films, skin
 * retouch on the portrait films. Numbers are first estimates to be tuned against test renders.
 */
public enum Looks {
    /** The auto develop alone (which already has a fine grain). */
    public static let natural = Look("natural", "Natural", nil)
    /** The default: suggested for portraits and everyday scenes. */
    public static let portra400 = Look("portra400", "Portra 400", "Kodak Portra 400.cube",
                                       grain: 20, bloom: 5, portraitRetouch: 20)
    public static let portra800 = Look("portra800", "Portra 800", "Kodak Portra 800.cube",
                                       grain: 35, bloom: 15, portraitRetouch: 20)
    public static let ektar100 = Look("ektar100", "Ektar 100", "Kodak Ektar 100.cube", grain: 10, highpass: 10)
    public static let gold200 = Look("gold200", "Gold 200", "Kodak Gold 200.cube", grain: 25, vignette: -10, warmth: 200)
    public static let superia400 = Look("superia400", "Superia 400", "Fuji Superia X-Tra 400.cube", grain: 25)
    public static let fuji400h = Look("fuji400h", "Fuji 400H", "Fuji Pro 400H.cube",
                                      grain: 20, bloom: 5, portraitRetouch: 20)
    /** Tungsten cinema film, the base of CineStill 800T. */
    public static let vision3500t = Look("vision500t", "Vision3 500T", "Kodak Vision3 500T.cube", grain: 35, bloom: 20)
    /** Slide film: vivid colour, deep shadows. */
    public static let velvia50 = Look("velvia50", "Velvia 50", "Fuji Velvia 50.cube", grain: 8, vignette: -10)
    public static let redscale = Look("redscale", "Redscale", "Redscale.png", contrast: 5, grain: 30, vignette: -15)
    /** Monochrome, classic: Tri-X on a normal paper grade. */
    public static let trix400 = Look("trix400", "Tri-X 400", "Kodak Tri-X 400.cube", grain: 25, monochrome: true)
    /** Monochrome, Tri-X developed longer: harder and grainier. */
    public static let trixPush = Look("trixpush", "Tri-X Push", "Kodak Tri-X 400 Push.cube", grain: 40, monochrome: true)
    /** Monochrome, hard: pushed Tri-X on a hard paper grade, deep blacks, bright whites. */
    public static let trixHard = Look("trixhard", "Tri-X Hard", "Kodak Tri-X 400 Hard.cube",
                                      grain: 30, vignette: -10, monochrome: true)
    /** Monochrome, Eastman Double-X cinema film. */
    public static let doubleX = Look("doublex", "Double-X", "Kodak Double-X 5222.cube", grain: 20, monochrome: true)
    /** Monochrome, soft: Double-X developed short on a soft paper grade, open shadows. */
    public static let doubleXSoft = Look("doublexsoft", "Double-X Soft", "Kodak Double-X 5222 Soft.cube",
                                         grain: 20, monochrome: true)

    public static let all: [Look] = [
        natural, portra400, portra800, ektar100, gold200, superia400, fuji400h,
        vision3500t, velvia50, redscale, trix400, trixPush, trixHard, doubleX, doubleXSoft,
    ]

    public static func byId(_ id: String) -> Look {
        let key = RetiredLooks.look(id)
        return all.first { $0.id == key } ?? natural
    }
}

/**
 * Looks on spektrafilm stocks (luts/spektrafilm, see tools/spektrafilm_luts/generate.py; ids match its STOCKS): RawBoy
 * Film's looks and Auto's Film mode. The stock replaces AgX and the LUT: negative, print and scan (slides: scan only),
 * with grain and halation (RawBoy's own in the standard apps, spektrafilm's in RawBoy Film). Looks add only skin
 * retouch on the portrait films. Mirrors Android's FilmLooks.
 */
public enum FilmLooks {
    private static func stock(_ id: String, _ name: String, portraitRetouch: Float = 0) -> Look {
        Look(id, name, nil, portraitRetouch: portraitRetouch, film: id)
    }

    public static let portra400 = stock("portra400", "Portra 400", portraitRetouch: 20)

    public static let all: [Look] = [
        Looks.natural,
        portra400,
        stock("portra800", "Portra 800", portraitRetouch: 20),
        stock("ektar100", "Ektar 100"),
        stock("gold200", "Gold 200"),
        stock("fuji400h", "Fuji 400H", portraitRetouch: 20),
        stock("xtra400", "X-Tra 400"),
        stock("vision250d", "Vision3 250D"),
        stock("vision500t", "Vision3 500T"),
        stock("velvia100", "Velvia 100"),
        stock("provia100", "Provia 100F"),
        stock("ektachrome100", "Ektachrome 100"),
        stock("kodachrome64", "Kodachrome 64"),
    ]

    public static func byId(_ id: String) -> Look {
        let key = RetiredLooks.stock(id)
        return all.first { $0.id == key } ?? portra400
    }
}
